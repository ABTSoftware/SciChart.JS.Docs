function createLayout(divElementId) {
    const root = document.getElementById(divElementId);
    root.style.cssText = "width:100%;height:100%;min-height:560px;display:grid;grid-template-rows:auto minmax(0,1fr);";
    root.innerHTML = `
        <div style="display:flex;align-items:center;gap:10px;flex-wrap:wrap;padding:8px;font-family:Arial,sans-serif;color:#888;">
            <strong style="font-size:14px;">Renko filter</strong>
            <button id="${divElementId}-source">Source OHLC</button>
            <button id="${divElementId}-filter">Renko</button>
            <label style="font-size:13px;">Brick <input id="${divElementId}-brick" type="number" min="0.001" max="0.02" step="0.001" value="${DEFAULT_BRICK_SIZE}" style="width:76px;"></label>
            <label style="font-size:13px;">Reversal <input id="${divElementId}-reversal" type="number" min="1" max="5" step="1" value="${DEFAULT_REVERSAL_AMOUNT}" style="width:52px;"></label>
            <span id="${divElementId}-count" style="font-size:13px;opacity:0.75;"></span>
        </div>
        <div id="${divElementId}-chart" style="width:100%;height:100%;min-height:0;"></div>
    `;
    return `${divElementId}-chart`;
}
async function drawExample(divElementId) {
    // #region_A_start
    const { DiscontinuousDateAxis, FastCandlestickRenderableSeries, MouseWheelZoomModifier, NumberRange, NumericAxis, OhlcDataSeries, RolloverModifier, SciChartSurface, SciChartJsNavyTheme, ZoomExtentsModifier, ZoomPanModifier } = SciChart; // or import from "scichart"
    const { OhlcRenkoFilter } = SciChartFinancialTools; // if using npm, import from "scichart-financial-tools";
    const chartDivId = createLayout(divElementId);
    const { sciChartSurface, wasmContext } = await SciChartSurface.create(chartDivId, {
        theme: new SciChartJsNavyTheme()
    });
    sciChartSurface.xAxes.add(new DiscontinuousDateAxis(wasmContext, { growBy: new NumberRange(0.02, 0.02) }));
    sciChartSurface.yAxes.add(new NumericAxis(wasmContext, { growBy: new NumberRange(0.02, 0.02), labelPrecision: 3 }));
    const sourceSeries = new OhlcDataSeries(wasmContext, {
        xValues: sourceData.xValues,
        openValues: sourceData.openValues,
        highValues: sourceData.highValues,
        lowValues: sourceData.lowValues,
        closeValues: sourceData.closeValues,
        dataSeriesName: "Source OHLC"
    });
    const renkoFilter = new OhlcRenkoFilter(sourceSeries, {
        dataSeriesName: "Renko",
        brickSize: DEFAULT_BRICK_SIZE,
        reversalAmount: DEFAULT_REVERSAL_AMOUNT
    });
    const candleSeries = new FastCandlestickRenderableSeries(wasmContext, {
        dataSeries: renkoFilter,
        dataPointWidth: 0.9,
        strokeThickness: 1
    });
    sciChartSurface.renderableSeries.add(candleSeries);
    sciChartSurface.chartModifiers.add(new ZoomPanModifier(), new ZoomExtentsModifier(), new MouseWheelZoomModifier(), new RolloverModifier());
    let usingRenko = true;
    const countLabel = document.getElementById(`${divElementId}-count`);
    const applyMode = () => {
        candleSeries.dataSeries = usingRenko ? renkoFilter : sourceSeries;
        countLabel.textContent = usingRenko
            ? `${renkoFilter.count()} Renko bricks from ${sourceSeries.count()} source bars`
            : `${sourceSeries.count()} source bars`;
        sciChartSurface.zoomExtents(300);
    };
    document.getElementById(`${divElementId}-source`).onclick = () => {
        usingRenko = false;
        applyMode();
    };
    document.getElementById(`${divElementId}-filter`).onclick = () => {
        usingRenko = true;
        applyMode();
    };
    document.getElementById(`${divElementId}-brick`).oninput = event => {
        if (event.target instanceof HTMLInputElement) {
            renkoFilter.brickSize = Number(event.target.value);
            applyMode();
        }
    };
    document.getElementById(`${divElementId}-reversal`).oninput = event => {
        if (event.target instanceof HTMLInputElement) {
            renkoFilter.reversalAmount = Number(event.target.value);
            applyMode();
        }
    };
    applyMode();
    // #region_A_end
}
drawExample("scichart-root");
